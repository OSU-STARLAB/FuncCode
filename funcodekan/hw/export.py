# checkpoint loading + CLI
# ---------------------------------------------------------------------------

def load_d2_wrapper(model_pt: Path, width=64, grid=5, order=3
                    ) -> QuantSplineKAN:
    ckpt = torch.load(model_pt, map_location="cpu", weights_only=True)
    wrapper = QuantSplineKAN(DenseSplineKAN(784, width, 10, grid, order))
    wrapper.load_state_dict(ckpt["state_dict"])
    return wrapper.eval()


def load_d3_wrapper(model_pt: Path, width=64, grid=5, order=3
                    ) -> QuantBranchKAN:
    ckpt = torch.load(model_pt, map_location="cpu", weights_only=True)
    branch = rebuild_branch_model(ckpt["clustered_export"], 784, width, 10,
                                  grid, order)
    wrapper = QuantBranchKAN(branch)
    wrapper.load_state_dict(ckpt["state_dict"])
    return wrapper.eval()


def _dense_fp32_acc(runs_dir: Path) -> float | None:
    summary = runs_dir / "branch_k32_s32_b16" / "summary.csv"
    if not summary.exists():
        return None
    import pandas as pd
    df = pd.read_csv(summary)
    row = df[df["stage"] == "dense_fp32"]
    return float(row["test_acc"].iloc[0]) if len(row) else None


def main(argv=None):
    p = argparse.ArgumentParser()
    p.add_argument("--design", required=True, choices=["d1", "d2", "d3"])
    p.add_argument("--runs-dir", type=str, default="runs_hw")
    p.add_argument("--out-root", type=str, default="hw/golden")
    p.add_argument("--seed", type=int, default=42)
    args = p.parse_args(argv)
    set_seed(args.seed)
    runs = Path(args.runs_dir)
    data = get_mnist_loaders(seed=args.seed, num_workers=0)
    dense_acc = _dense_fp32_acc(runs)
    if args.design == "d1":
        ckpt = torch.load(runs / "branch_k32_s32_b16" / "dense.pt",
                          map_location="cpu", weights_only=True)
        dense = DenseSplineKAN(784, 64, 10, 5, 3)
        dense.load_state_dict(ckpt["model"])
        m = export_d1(dense, data.test_loader,
                      Path(args.out_root) / "fp32")
    elif args.design == "d2":
        wrapper = load_d2_wrapper(runs / "d2_lsq_w4a4" / "model.pt")
        m = export_d2(wrapper, data.test_loader,
                      Path(args.out_root) / "lsq_w4a4", dense_acc)
    else:
        wrapper = load_d3_wrapper(runs / "d3_funccode_w4a4" / "model.pt")
        m = export_d3(wrapper, data.test_loader,
                      Path(args.out_root) / "funccode_w4a4", dense_acc)
    l1 = m.get("l1", {})
    print(f"[export] {args.design}: L1 passed={l1.get('passed')} "
          f"emulator_acc={l1.get('emulator_acc', l1.get('numpy_acc'))}")
    if not l1.get("passed"):
        raise SystemExit(f"L1 FAILED for {args.design} — see verification log")


if __name__ == "__main__":
    main()
